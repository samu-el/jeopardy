import { defineConfig, defineRule, type AgentlintNode } from "@aurelienbbn/agentlint";

/**
 * Repository rules from AGENTS.md and design.md. Each one names a code shape a reviewer
 * kept correcting; agentlint stops the turn until the code changes or a reason is recorded.
 *
 * This file and the em dash test spell the characters they look for as escapes, so both
 * stay out of the em dash binding.
 */

const agentsGuide = { type: "file", path: "AGENTS.md" } as const;
const designGuide = { type: "file", path: "design.md" } as const;

/** Every grammar agentlint parses: TS/JS through `program`, JSON through `document`. */
const rootTypes = ["program", "document"] as const;

/** Deepest nodes whose text matches `re` while none of their children do on their own. */
function deepestMatches(
  node: AgentlintNode,
  re: RegExp,
  out: AgentlintNode[] = [],
): AgentlintNode[] {
  if (!re.test(node.text)) return out;
  const matching = node.children.filter((child) => re.test(child.text));
  if (matching.length === 0) out.push(node);
  for (const child of matching) deepestMatches(child, re, out);
  return out;
}

/** Text a user reads: string contents, JSX text and escapes. Comments and code are not copy. */
const copyNodeTypes = [
  "string_fragment",
  "jsx_text",
  "escape_sequence",
  "html_character_reference",
] as const;

function onCopy(handler: (node: AgentlintNode) => void) {
  return Object.fromEntries(copyNodeTypes.map((type) => [type, handler]));
}

// 1. No em dashes ------------------------------------------------------------------------

/** The character itself, its HTML entities and its JS escapes. */
const emDash = /\u2014|&mdash;|&#8212;|&#x2014;|\\u2014|\\u\{2014\}/i;

const noEmDash = defineRule({
  lifecycle: "state",
  standard: {
    id: "copy/no-em-dash",
    revision: 1,
    title: "No em dashes anywhere",
    source: agentsGuide,
    guidance: {
      standard:
        "UI copy, docs, comments, tests and data never contain an em dash (U+2014), its HTML entity or its escape.",
      checks: [
        "Rewrite the sentence with a period, comma, colon or parentheses. An en dash in a range (0.8 to 1.2, 1-5) is fine.",
      ],
      examples: [
        { label: "Colon", code: '"Too close to call: the host rules"' },
        {
          label: "Two sentences",
          code: "// The room owns the clock. Clients only render it.",
        },
      ],
    },
  },
  detector: {
    id: "text/em-dash",
    version: 1,
    scan: "file",
    createOnce({ context }) {
      const visit = (root: AgentlintNode) => {
        for (const node of deepestMatches(root, emDash)) {
          context.report({
            node,
            message: "An em dash: rewrite with a period, comma, colon or parentheses.",
          });
        }
      };
      return Object.fromEntries(rootTypes.map((type) => [type, visit]));
    },
    fixtures: {
      mustReport: [
        "const title = 'Final Jeopardy \u2014 wagers';",
        "// The room owns the clock \u2014 clients render it.",
        "export const Line = () => <p>Wait &mdash; the host rules</p>;",
        "const dash = '\\u2014';",
        { file: "fixture.json", source: '{ "label": "Round one \u2014 Jeopardy" }' },
      ],
      mustStaySilent: [
        "const title = 'Final Jeopardy: wagers';",
        "const range = 'Reading speed, 0.8\u20131.2';",
        { file: "fixture.json", source: '{ "label": "Round one: Jeopardy" }' },
      ],
    },
  },
  binding: {
    id: "copy/no-em-dash",
    authority: "human",
    include: ["**/*.{ts,tsx,js,jsx,mjs,cjs,mts,cts,json}"],
    exclude: [
      // Both spell the character on purpose, to find it.
      ".agentlint/config.ts",
      "tests/unit/foundation/em-dash.test.ts",
      // Regenerated by Next on every build.
      "next-env.d.ts",
    ],
  },
});

// 2. Cut taglines, helper text and secondary labels -------------------------------------

/** Props that exist to carry a line of explanation under or beside a control. */
const helperProps = new Set([
  "helperText",
  "description",
  "subtitle",
  "subheader",
  "secondary",
  "caption",
  "tagline",
  "eyebrow",
  "hint",
  "subtext",
  "supportingText",
]);

/** A fixed string: `"..."`, `{"..."}` or a template literal with nothing substituted. */
function isStaticString(value: AgentlintNode | undefined): boolean {
  if (!value) return false;
  if (value.type === "string") return true;
  if (value.type === "template_string")
    return value.descendantsOfType("template_substitution").length === 0;
  if (value.type === "jsx_expression") {
    const inner = value.children.filter((child) => child.isNamed);
    return inner.length === 1 && isStaticString(inner[0]);
  }
  return false;
}

const noHelperTextStandard = {
  id: "ui/no-helper-text",
  revision: 1,
  title: "No taglines, helper text or secondary labels",
  source: agentsGuide,
  guidance: {
    standard:
      "A screen makes sense from its controls, headings and data. When it needs a line of explanation, the layout changes instead.",
    checks: [
      "Data, status, errors, counters and empty states the user acts on are not helper text: accept with what the text reports.",
      "Explanations of what a control does belong in its label, its grouping or its order on the screen.",
    ],
    examples: [
      {
        label: "Error, not a hint",
        code: "<TextField error={invalid} helperText={invalid ? fieldError : undefined} />",
      },
      {
        label: "Data in a quiet tone",
        code: '<Typography variant="caption" color="text.secondary">{airDate}</Typography>',
      },
    ],
  },
} as const;

const noHelperProps = defineRule({
  lifecycle: "state",
  standard: noHelperTextStandard,
  detector: {
    id: "jsx/static-helper-prop",
    version: 1,
    scan: "file",
    createOnce({ context }) {
      return {
        jsx_attribute(node) {
          const [name, ...rest] = node.children.filter((child) => child.isNamed);
          if (!name || !helperProps.has(name.text)) return;
          if (!isStaticString(rest.at(-1))) return;
          context.report({
            node,
            message: `A fixed ${name.text}: say it with the layout or the label instead.`,
          });
        },
      };
    },
    fixtures: {
      mustReport: [
        'export const F = () => <TextField label="Name" helperText="Shown to the other players" />;',
        "export const C = () => <CardHeader title=\"Lobby\" subheader={'Invite friends to play'} />;",
        "export const L = () => <ListItemText primary={name} secondary={`Joined the room`} />;",
      ],
      mustStaySilent: [
        'export const F = () => <TextField label="Name" error={bad} helperText={bad ? message : undefined} />;',
        "export const L = () => <ListItemText primary={name} secondary={`${score} points`} />;",
        'export const T = () => <Tooltip title="Copy the link"><span /></Tooltip>;',
      ],
    },
  },
  binding: {
    id: "ui/no-helper-text/props",
    authority: "agent",
    include: ["src/**/*.tsx"],
  },
});

const quietVariants = new Set(["caption", "body2", "subtitle2"]);
const quietTone = /text\.secondary|inkMuted|inkFaint/;

function attributeValue(opening: AgentlintNode, attribute: string): string | undefined {
  for (const attr of opening.childrenByType("jsx_attribute")) {
    const [name, value] = attr.children.filter((child) => child.isNamed);
    if (name?.text === attribute) return value?.text ?? "";
  }
  return undefined;
}

const noQuietStaticLine = defineRule({
  lifecycle: "state",
  standard: noHelperTextStandard,
  detector: {
    id: "mui/static-quiet-typography",
    version: 1,
    scan: "file",
    createOnce({ context }) {
      return {
        jsx_element(node) {
          const opening = node.childByFieldName("open_tag");
          if (opening?.childByFieldName("name")?.text !== "Typography") return;
          const variant = attributeValue(opening, "variant")?.replace(/["'{}]/g, "");
          if (!variant || !quietVariants.has(variant)) return;
          const tone = `${attributeValue(opening, "color") ?? ""} ${attributeValue(opening, "sx") ?? ""}`;
          if (!quietTone.test(tone)) return;
          const body = node.children.filter(
            (child) =>
              child.type !== "jsx_opening_element" &&
              child.type !== "jsx_closing_element",
          );
          const prose = body.every(
            (child) =>
              child.type === "jsx_text" || child.type === "html_character_reference",
          );
          if (!prose || !body.some((child) => child.text.trim() !== "")) return;
          context.report({
            node,
            message: "A fixed line in a quiet tone reads as helper text.",
          });
        },
      };
    },
    fixtures: {
      mustReport: [
        'export const H = () => <Typography variant="caption" color="text.secondary">Pick a game to start</Typography>;',
        'export const H = () => <Typography variant="body2" sx={{ color: ui.inkMuted }}>Everyone plays on their own phone</Typography>;',
      ],
      mustStaySilent: [
        'export const D = () => <Typography variant="caption" color="text.secondary">{episode.airDate}</Typography>;',
        'export const S = () => <Typography variant="caption" sx={{ color: ui.inkMuted }}>Next clue in {seconds}s</Typography>;',
        'export const T = () => <Typography variant="h2">Final Jeopardy</Typography>;',
      ],
    },
  },
  binding: {
    id: "ui/no-helper-text/quiet-typography",
    authority: "agent",
    include: ["src/**/*.tsx"],
  },
});

// 3. Meta never joins with a middle dot -------------------------------------------------

/** A middle dot standing alone between words, or spelled as an entity or escape. */
const middleDot = /(?:^|\s)\u00b7(?:\s|$)|&middot;|&#183;|&#xb7;|\\u00b7|\\u\{b7\}/i;

const noMiddleDotMeta = defineRule({
  lifecycle: "state",
  standard: {
    id: "ui/no-middle-dot-meta",
    revision: 1,
    title: "Meta never joins with a middle dot",
    source: designGuide,
    guidance: {
      standard:
        "Separate pieces of meta with a gap, a list or a table. In plain text (chat, notices, speech), write a phrase.",
      checks: ["In JSX, render the parts as separate elements, e.g. with MetaParts."],
      examples: [
        {
          label: "Parts with a gap",
          code: '<MetaParts parts={[episode.airDate, episode.info]} gap="1em" />',
        },
        {
          label: "Plain text",
          code: "`${name}: ${quotedAnswer(answer)} (${percent}%)`",
        },
      ],
    },
  },
  detector: {
    id: "text/middle-dot-join",
    version: 1,
    scan: "file",
    createOnce({ context }) {
      return onCopy((node) => {
        if (!middleDot.test(node.text)) return;
        context.report({
          node,
          message: "Meta joined with a middle dot: separate the parts instead.",
        });
      });
    },
    fixtures: {
      mustReport: [
        "const meta = parts.join(' \u00b7 ');",
        "const line = `${name} \u00b7 ${score}`;",
        "export const M = () => <span>{airDate} &middot; {info}</span>;",
      ],
      mustStaySilent: [
        "const line = `${name}: ${score}`;",
        "// Hallmark \u00b7 notes in a comment are not UI copy.",
      ],
    },
  },
  binding: {
    id: "ui/no-middle-dot-meta",
    authority: "agent",
    include: ["src/**/*.{ts,tsx}", "workers/**/*.ts"],
  },
});

// Player faces are icons or initials, never emoji -----------------------------------------

/** Pictographic emoji, leaving out the text symbols (c), (r) and TM. */
const emoji = /(?![\u00a9\u00ae\u2122])\p{Extended_Pictographic}|\\u\{1f[0-9a-f]{3}\}|\\ud83[c-e]/iu;

/** Places the old avatar shape stored an emoji: `emoji: "..."`, `emoji?: string`, `emoji=` and `{ emoji }`. */
function emojiField(node: AgentlintNode): boolean {
  switch (node.type) {
    case "pair":
    case "property_signature":
    case "jsx_attribute": {
      const key = node.children.find((child) => child.isNamed);
      if (key?.text.replace(/["']/g, "") !== "emoji") return false;
      if (node.type !== "property_signature") return true;
      const type = node.childByFieldName("type")?.text.replace(/^:\s*/, "");
      return type !== "unknown" && type !== "never";
    }
    case "shorthand_property_identifier":
    case "shorthand_property_identifier_pattern":
      return node.text === "emoji";
    default:
      return false;
  }
}

const noEmojiFaces = defineRule({
  lifecycle: "state",
  standard: {
    id: "ui/no-emoji",
    revision: 1,
    title: "Player faces are icons or initials, never emoji",
    source: designGuide,
    guidance: {
      standard:
        "A player's face is a PlayerAvatar key: a filled Material icon from avatarIcons, or their initial, on their colour. The UI draws icons, not emoji.",
      checks: [
        "Add a new face to avatarIcons and its glyph in PlayerAvatar.",
        "Legacy `emoji` fields are only read to drop them (typed unknown), never stored or rendered.",
      ],
      examples: [
        { label: "Icon key", code: 'setPlayerAvatar(playerId, { avatar: "rocket" })' },
        { label: "Material icon", code: '<EmojiEventsIcon fontSize="small" />' },
      ],
    },
  },
  detector: {
    id: "ts/emoji-literal-or-field",
    version: 1,
    scan: "file",
    createOnce({ context }) {
      const field = (node: AgentlintNode) => {
        if (emojiField(node))
          context.report({
            node,
            message: "An emoji field: faces are PlayerAvatar keys.",
          });
      };
      return {
        ...onCopy((node) => {
          if (emoji.test(node.text))
            context.report({
              node,
              message: "An emoji in the UI: use a Material icon.",
            });
        }),
        pair: field,
        property_signature: field,
        jsx_attribute: field,
        shorthand_property_identifier: field,
        shorthand_property_identifier_pattern: field,
      };
    },
    fixtures: {
      mustReport: [
        "const faces = ['\u{1F98A}', '\u{1F680}'];",
        "setPlayerAvatar(id, { emoji: entry });",
        "interface Player { emoji?: string }",
        "export const A = ({ emoji }: Props) => <span>{emoji}</span>;",
        "export const Trophy = () => <span>\u{1F3C6}</span>;",
      ],
      mustStaySilent: [
        "setPlayerAvatar(id, { avatar: 'rocket' });",
        "const copy: GamePlayer & { emoji?: unknown } = { ...player }; delete copy.emoji;",
        "const verdict = `\u2713 ${name}`;",
        "const notice = '\u00a9 2026';",
      ],
    },
  },
  binding: {
    id: "ui/no-emoji",
    authority: "agent",
    include: ["src/**/*.{ts,tsx}", "workers/**/*.ts"],
  },
});

// Zustand holds public snapshots and UI state, never the authoritative game ----------------

/** The authoritative state type and the calls that build or advance it. */
const authoritative = new Set([
  "GameState",
  "createGame",
  "dispatchGameCommand",
  "InMemoryRealtimeRoom",
]);

const noAuthoritativeStateInZustand = defineRule({
  lifecycle: "state",
  standard: {
    id: "state/no-authoritative-state-in-zustand",
    revision: 1,
    title: "Zustand holds public snapshots, never the authoritative game",
    source: agentsGuide,
    guidance: {
      standard:
        "Zustand stores keep client UI and session state and the room's PublicGameState. Rules, private room state and the engine live in the room (src/lib/game, src/lib/realtime) behind a RoomRuntime.",
      checks: [
        "A store reaches the game through runtime.sendCommand and receives PublicGameState back.",
      ],
      examples: [
        {
          label: "Public snapshot",
          code: "setPublicState: (state: PublicGameState) => set({ publicState: state })",
        },
      ],
    },
  },
  detector: {
    id: "zustand/authoritative-game-reference",
    version: 1,
    scan: "file",
    createOnce({ context }) {
      let usesZustand = false;
      const check = (node: AgentlintNode) => {
        if (usesZustand && authoritative.has(node.text)) {
          context.report({
            node,
            message: `${node.text} in a Zustand module: keep the authoritative game in the room.`,
          });
        }
      };
      return {
        before() {
          usesZustand = /from\s+["']zustand(?:\/[^"']*)?["']/.test(context.source);
        },
        type_identifier: check,
        identifier: check,
      };
    },
    fixtures: {
      mustReport: [
        'import { create } from "zustand";\nimport type { GameState } from "@/lib/game";\nexport const useStore = create<{ game: GameState | null }>(() => ({ game: null }));',
        'import { create } from "zustand";\nimport { createGame } from "@/lib/game";\nexport const useStore = create(() => ({ game: createGame(input) }));',
      ],
      mustStaySilent: [
        'import { create } from "zustand";\nimport type { PublicGameState } from "@/lib/game";\nexport const useStore = create<{ publicState: PublicGameState | null }>(() => ({ publicState: null }));',
        'import type { GameState } from "./contracts";\nexport function createGame(): GameState { return state; }',
      ],
    },
  },
  binding: {
    id: "state/no-authoritative-state-in-zustand",
    authority: "human",
    include: ["src/**/*.{ts,tsx}"],
  },
});

