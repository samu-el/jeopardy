/**
 * No em dashes (AGENTS.md), for the files agentlint cannot parse.
 *
 * agentlint's `copy/no-em-dash` rule covers TS, JS and JSON. This covers the
 * rest the repo tracks: Markdown, CSS, HTML, SVG, YAML, TOML and the like.
 */
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync } from "node:fs";
import { extname } from "node:path";
import { describe, expect, it } from "vitest";

/** Parsed by agentlint, so `copy/no-em-dash` owns them. */
const agentlintTypes = new Set([
  ".ts",
  ".tsx",
  ".js",
  ".jsx",
  ".mjs",
  ".cjs",
  ".mts",
  ".cts",
  ".json",
]);

/** Regenerated by a tool, never edited by hand. */
const generated = new Set(["bun.lock"]);

const emDash = /\u2014|&mdash;|&#8212;|&#x2014;|\\u2014|\\u\{2014\}/i;

function trackedFiles(): string[] {
  const listed = execFileSync(
    "git",
    ["ls-files", "-z", "--cached", "--others", "--exclude-standard"],
    {
      encoding: "utf8",
    },
  );
  return listed
    .split("\0")
    .filter(Boolean)
    .filter(
      (file) =>
        !agentlintTypes.has(extname(file)) && !generated.has(file) && existsSync(file),
    );
}

describe("em dashes outside agentlint's grammars", () => {
  it("appear in no tracked text file", () => {
    const hits: string[] = [];
    for (const file of trackedFiles()) {
      const bytes = readFileSync(file);
      if (bytes.includes(0)) continue; // Images and fonts.
      bytes
        .toString("utf8")
        .split("\n")
        .forEach((line, index) => {
          if (emDash.test(line)) hits.push(`${file}:${index + 1}`);
        });
    }
    expect(hits).toEqual([]);
  });
});
